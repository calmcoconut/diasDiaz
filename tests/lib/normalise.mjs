/* tests/lib/normalise.mjs
   ---------------------------------------------------------------------------
   The one normaliser. Applied to BOTH the pinned golden file and the freshly
   built output before they are compared, so a rule change can only ever be a
   deliberate edit of this file.

   Every rule below exists because it caused real churn: a constant that moves
   with the machine, the Hugo version, the asset hash or the clock must never
   appear in a golden diff, because then the diff stops being reviewable and
   the suite gets muted.

   Rules, in order (order matters):

     1. URL origins        a baseURL flip once rewrote 235 files
     2. asset hashes       .<64 hex>.js|.css moves with every asset edit
     3. MathML             KaTeX/MathML markup is Hugo-version-coupled and is
                           the single largest churn source
     4. inline SVG         every callout icon is about 1 KB of <path> data
     5. date stamps        RSS lastBuildDate is the build clock
     6. whitespace         whitespace-only lines dropped, 3+ newlines
                           collapsed, trailing spaces stripped

   Normalisation is not a substitute for a stable site: if a golden has to be
   regenerated by `node tests/lib/update.mjs` and the only change in it is
   [MATHML] or [SVG], the rule is hiding a real regression and the rule should
   be revisited.

   No dependencies: node:fs is the caller's business, this module is pure.
*/

/** Human-readable list of the rules, in application order. Used by the
 *  golden test to describe itself and by the update script's report.
 */
export const NORMALISATION_RULES = [
  "URL origin  ->  https://ORIGIN",
  "asset hash  ->  .<HASH>.js|.css",
  "<math>/katex -> [MATHML]",
  "<svg>       -> [SVG]",
  "<lastBuildDate> -> [DATE]",
  "whitespace  ->  drop blank lines, collapse 3+ newlines, trim EOL spaces",
];

/**
 * Normalise a rendered HTML document so it can be pinned and compared.
 *
 * @param {string} input rendered output
 * @returns {string} normalised text, with exactly one trailing newline
 */
export function normalise(input) {
  let out = String(input).replace(/\r\n?/g, "\n");

  // 1. Any absolute URL collapses to one origin. This is why the harness pins
  //    --baseURL on every invocation: without the pin a baseURL change lands in
  //    hundreds of files at once.
  out = out.replace(/https?:\/\/[^"'\s/]+/g, "https://ORIGIN");

  // 2. Fingerprinted asset filenames (Hugo emits 64 hex chars).
  out = out.replace(/\.[0-9a-f]{64}\.(js|css)/g, ".<HASH>.$1");

  // 3. Math. <math> first: the KaTeX wrapper is a <span> around it, so
  //    matching the wrapper first would leave a stray closing tag behind.
  out = out.replace(/<math[\s\S]*?<\/math>/g, "[MATHML]");
  out = out.replace(/<span class="katex">[\s\S]*?<\/span>/g, "[MATHML]");

  // 4. Inline SVG (callout icons, pixel-art icons).
  out = out.replace(/<svg[\s\S]*?<\/svg>/g, "[SVG]");

  // 5. RSS build clock.
  out = out.replace(
    /<lastBuildDate>.*?<\/lastBuildDate>/g,
    "<lastBuildDate>[DATE]</lastBuildDate>",
  );

  // 6. Whitespace stability.
  out = out
    .split("\n")
    .map((line) => line.replace(/[ \t]+$/, ""))
    .filter((line) => line.trim() !== "")
    .join("\n");
  out = out.replace(/\n{3,}/g, "\n\n");

  return `${out.trim()}\n`;
}

/**
 * Compare two normalised documents and describe the first differences.
 * Kept here (not in the test file) so the update script can report the same
 * way. Returns an empty array when the documents are equal.
 *
 * @param {string} expected
 * @param {string} actual
 * @param {{limit?: number}} [options]
 * @returns {string[]} human-readable difference lines
 */
export function describeDifference(expected, actual, options = {}) {
  const limit = options.limit ?? 20;
  const want = expected.split("\n");
  const got = actual.split("\n");
  const lines = [];
  const max = Math.max(want.length, got.length);
  for (let i = 0; i < max && lines.length < limit; i += 1) {
    if (want[i] !== got[i]) {
      lines.push(`line ${i + 1}:`);
      if (want[i] !== undefined) lines.push(`  golden: ${want[i]}`);
      if (got[i] !== undefined) lines.push(`  actual: ${got[i]}`);
    }
  }
  if (want.length !== got.length) {
    lines.push(`line count: golden ${want.length}, actual ${got.length}`);
  }
  return lines;
}
